"""Render an engine-authored case package's ontology as Markdown: a mermaid class diagram plus the compiled DoD.

    python eval/ontology_diagram.py CASE_DIR [--title TITLE]

Reads CASE_DIR/02-ontology/ontology.json and dod-queries.json, and CASE_DIR/01-scope/prd.json, exactly as the engine
wrote them, and prints Markdown. Nothing is inferred beyond what those files state: DoD properties are marked with
`*`, relations are drawn with their declared domain and range, and a criterion the engine set aside is listed as such.
"""

import argparse
import json
import re
from pathlib import Path


def ident(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", value)


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def diagram(onto: dict) -> str:
    primary = onto.get("primary_class")
    props: dict[str, list[dict]] = {}
    for prop in onto.get("properties") or []:
        props.setdefault(prop.get("domain"), []).append(prop)
    lines = ["```mermaid", "classDiagram", "  direction LR"]
    for cls in onto.get("classes") or []:
        cid = cls["id"]
        lines.append(f"  class {ident(cid)} {{")
        if cid == primary:
            lines.append("    <<primary>>")
        for prop in props.get(cid, []):
            mark = "*" if prop.get("dod") else ""
            lines.append(f"    {ident(str(prop.get('datatype') or 'value'))} {ident(prop['id'])}{mark}")
        lines.append("  }")
    for rel in onto.get("relations") or []:
        label = re.sub(r"[\"#;]", " ", str(rel.get("label") or rel["id"]))
        lines.append(f"  {ident(rel['domain'])} --> {ident(rel['range'])} : {label}")
    lines.append("```")
    return "\n".join(lines)


def dod_table(prd: dict, queries: dict) -> str:
    compiled = {q["criterion_id"]: q for q in queries.get("queries") or []}
    rows = ["| Criterion (approved PRD) | Target | Compiled query |", "|---|---|---|"]
    for crit in prd.get("definition_of_done") or []:
        q = compiled.get(crit["id"])
        target = f"{crit.get('operator')} {crit.get('target')}"
        if crit.get("min_ratio") is not None:
            target += f" (min_ratio {crit['min_ratio']})"
        if q is None:
            how = "set aside by the engine: not expressible over the ontology"
        else:
            scope = q.get("class") or q.get("class_id") or ""
            extra = f", via `{q['relation_id']}`" if q.get("relation_id") else ""
            how = f"`{q.get('aggregate')}` on `{scope}`{extra}".replace(" on ``", "")
        metric = str(crit.get("metric", "")).replace("|", "/")
        rows.append(f"| {crit['id']}: {metric} | {target} | {how} |")
    return "\n".join(rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("case_dir", type=Path)
    ap.add_argument("--title")
    args = ap.parse_args()
    case = args.case_dir
    onto = load(case / "02-ontology" / "ontology.json")
    prd = load(case / "01-scope" / "prd.json")
    queries = load(case / "02-ontology" / "dod-queries.json")
    gen = onto.get("generated_by") or {}
    print(f"### {args.title or case.name}\n")
    print(
        f"Primary class `{onto.get('primary_class')}` · {len(onto.get('classes') or [])} classes · "
        f"{len(onto.get('properties') or [])} properties · {len(onto.get('relations') or [])} relations · "
        f"{len(onto.get('rules') or [])} rules"
        + (f" · generated by `{gen.get('model')}` ({gen.get('backend')})" if gen.get("model") else "")
        + ". `*` marks a definition-of-done property.\n"
    )
    print(diagram(onto) + "\n")
    print(dod_table(prd, queries) + "\n")


if __name__ == "__main__":
    main()
